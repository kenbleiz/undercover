export const copy: Record<Lang, typeof fr> = { fr, en };

export function t(lang: Lang) {
  return copy[lang];
}

export function categoryLabel(lang: Lang, c: Category): string {
  const x = t(lang);
  const map: Record<Category, string> = {
    everyday: x.catEveryday,
    food: x.catFood,
    places: x.catPlaces,
    nature: x.catNature,
    objects: x.catObjects,
    culture: x.catCulture,
    manga: x.catManga,
  };
  return map[c];
}

export function roleLabel(lang: Lang, role: Role): string {
  const x = t(lang);
  if (role === "civilian") return x.roleCivilian;
  if (role === "undercover") return x.roleUndercover;
  return x.roleMrWhite;
}

export function winnerTitle(lang: Lang, winner: Winner): string {
  const x = t(lang);
  if (winner === "civilians") return x.civiliansWin;
  if (winner === "undercover") return x.undercoverWin;
  return x.mrWhiteWin;
}
